func TestCompletionCommand(t *testing.T) {
	for _, test := range []struct {
		args []string
		code int
	}{
		{nil, 2}, {[]string{"fish"}, 2}, {[]string{"zsh"}, 2},
		{[]string{"bash", "extra"}, 2}, {[]string{"--help", "extra"}, 2},
		{[]string{"bash", "--help"}, 2}, {[]string{"bash", "--output", "file"}, 2},
		{[]string{"--help"}, 0}, {[]string{"-h"}, 0}, {[]string{"help"}, 0},
		{[]string{"bash"}, 0},
	} {
		t.Run(strings.Join(test.args, "_"), func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := completionCommand(test.args, &stdout, &stderr); code != test.code {
				t.Fatalf("code=%d, want %d; stderr=%s", code, test.code, &stderr)
			}
			if reflect.DeepEqual(test.args, []string{"bash"}) {
				if stdout.String() != bashCompletionScript || stderr.Len() != 0 {
					t.Fatalf("generation output differs: stdout=%q stderr=%q", &stdout, &stderr)
				}
			} else if stdout.Len() != 0 || !strings.Contains(stderr.String(), "usage: logc completion bash") {
				t.Fatalf("stdout=%q stderr=%q", &stdout, &stderr)
			}
		})
	}
}

type completionFailWriter struct{}

func (completionFailWriter) Write([]byte) (int, error) {
	return 0, errors.New("injected output failure")
}

func TestCompletionWriteFailure(t *testing.T) {
	var stderr bytes.Buffer
	if code := completionCommand([]string{"bash"}, completionFailWriter{}, &stderr); code != 1 || !strings.Contains(stderr.String(), "injected output failure") {
		t.Fatalf("code=%d stderr=%q", code, &stderr)
	}
}

func TestCompletionBash(t *testing.T) {
	if _, err := os.Stat("/bin/bash"); err != nil {
		t.Skip("/bin/bash unavailable")
	}
	var generated bytes.Buffer
	if code := completionCommand([]string{"bash"}, &generated, io.Discard); code != 0 {
		t.Fatalf("generation code=%d", code)
	}
	script := filepath.Join(t.TempDir(), "completion.bash")
	if err := os.WriteFile(script, generated.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	run := func(args ...string) string {
		t.Helper()
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		command := exec.CommandContext(ctx, "/bin/bash", append([]string{"--noprofile", "--norc"}, args...)...)
		var stdout, stderr bytes.Buffer
		command.Stdout, command.Stderr = &stdout, &stderr
		if err := command.Run(); err != nil || stderr.Len() != 0 {
			t.Fatalf("bash: %v; stdout=%s stderr=%s", err, &stdout, &stderr)
		}
		return stdout.String()
	}
	run("-n", script)
	registration := run("-c", `. "$1"; complete -p logc`, "bash", script)
	for _, option := range []string{"-o default", "-o bashdefault", "-F _logc_completion logc"} {
		if !strings.Contains(registration, option) {
			t.Fatalf("registration %q lacks %q", registration, option)
		}
	}
	for _, test := range []struct {
		name  string
		words []string
		want  []string
		omit  []string
		empty bool
	}{
		{name: "root commands", words: []string{"logc", ""}, want: []string{"watch", "docker", "completion", "--all", "--json", "--version"}},
		{name: "root prefix", words: []string{"logc", "co"}, want: []string{"config", "completion"}},
		{name: "version only at first argument", words: []string{"logc", "api", "--"}, omit: []string{"--version"}, want: []string{"--all"}},
		{name: "version not after flag", words: []string{"logc", "--json", "--"}, omit: []string{"--version"}, want: []string{"--all"}},
		{name: "root flags", words: []string{"logc", "--"}, want: []string{"--since", "--category", "--exclude"}, omit: []string{"watch", "--kernel", "--tail"}},
		{name: "watch", words: []string{"logc", "watch", "--"}, want: []string{"--full", "--since", "--module"}, omit: []string{"--all", "--json", "--kernel", "--tail"}},
		{name: "system", words: []string{"logc", "system", "--"}, want: []string{"--kernel", "--all", "--json"}, omit: []string{"--tail", "--full"}},
		{name: "docker", words: []string{"logc", "docker", ""}, want: []string{"--since", "--until", "--tail", "-n", "--timestamps", "-t", "--details", "--follow", "-f", "-m", "-i", "-C", "--dedup", "--no-color", "--json"}, omit: []string{"--all", "--lines", "--category", "--module", "--current", "watch"}},
		{name: "ls", words: []string{"logc", "ls", "--"}, want: []string{"--json", "--category", "--module"}, omit: []string{"--since", "--help", "--all"}},
		{name: "list alias", words: []string{"logc", "list", "--"}, want: []string{"--json", "--category", "--module"}},
		{name: "where", words: []string{"logc", "where", "--"}, want: []string{"--json"}, omit: []string{"--since", "--help"}},
		{name: "config", words: []string{"logc", "config", ""}, want: []string{"init", "path", "show"}, omit: []string{"bash", "--force", "--json"}},
		{name: "config init", words: []string{"logc", "config", "init", ""}, want: []string{"--force"}, omit: []string{"--help", "path", "--json"}},
		{name: "config path", words: []string{"logc", "config", "path", ""}, empty: true},
		{name: "config show", words: []string{"logc", "config", "show", ""}, empty: true},
		{name: "config force used", words: []string{"logc", "config", "init", "--force", ""}, empty: true},
		{name: "completion", words: []string{"logc", "completion", ""}, want: []string{"bash", "--help"}, omit: []string{"zsh", "fish", "--output", "--json"}},
		{name: "completion done", words: []string{"logc", "completion", "bash", ""}, empty: true},
		{name: "later target is not command", words: []string{"logc", "api", "docker", "--"}, want: []string{"--category", "--all"}, omit: []string{"--tail"}},
		{name: "root docker value", words: []string{"logc", "-m", "docker", "--"}, want: []string{"--category", "--all"}, omit: []string{"--tail"}},
		{name: "root watch value", words: []string{"logc", "--module", "watch", "--"}, want: []string{"--all", "--json"}},
		{name: "docker watch value", words: []string{"logc", "docker", "-m", "watch", "--"}, want: []string{"--tail"}, omit: []string{"--full"}},
		{name: "double dash", words: []string{"logc", "--", ""}, empty: true},
		{name: "docker double dash", words: []string{"logc", "docker", "--", "--"}, empty: true},
		{name: "dash consumed as value", words: []string{"logc", "-m", "--", "--"}, want: []string{"--all"}},
		{name: "path with spaces", words: []string{"logc", "/tmp/log directory/ap"}, empty: true},
		{name: "docker equals value", words: []string{"logc", "docker", "--tail=10", "--"}, want: []string{"--tail"}},
		{name: "docker split equals empty", words: []string{"logc", "docker", "--since", "=", ""}, empty: true},
		{name: "docker split equals prefix", words: []string{"logc", "docker", "--until", "=", "--"}, empty: true},
		{name: "docker split equals tail", words: []string{"logc", "docker", "--tail", "=", "doc"}, empty: true},
		{name: "docker split equals value consumed", words: []string{"logc", "docker", "--since", "=", "watch", "--"}, want: []string{"--tail"}, omit: []string{"--full"}},
		{name: "docker synthetic split colon continuation", words: []string{"logc", "docker", "--since", "=", "12", ":", "-"}, empty: true},
		{name: "docker synthetic split colon until", words: []string{"logc", "docker", "--until", "12", ":", "--"}, empty: true},
		{name: "docker synthetic split colon consumed", words: []string{"logc", "docker", "--since", "=", "12", ":", "30", "--"}, want: []string{"--tail"}},
		{name: "docker intact colon current value", words: []string{"logc", "docker", "--since", "12:-"}, empty: true},
		{name: "docker intact colon consumed", words: []string{"logc", "docker", "--since", "12:30", "--"}, want: []string{"--tail"}},
		{name: "root synthetic split regex colon", words: []string{"logc", "-m", "error", ":", "-"}, empty: true},
		{name: "docker colon outside value", words: []string{"logc", "docker", "container", ":", "--"}, want: []string{"--tail"}},
		{name: "version done", words: []string{"logc", "version", ""}, empty: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			args := append([]string{"-c", `. "$1"
PATH=/nonexistent
command_not_found_handle() { printf 'unexpected command: %s\n' "$*" >&2; return 127; }
shift
COMP_WORDS=("$@")
COMP_CWORD=$((${#COMP_WORDS[@]} - 1))
_logc_completion
printf '%s\n' "${COMPREPLY[@]}"`, "bash", script}, test.words...)
			output := run(args...)
			got := strings.Fields(output)
			if test.empty && len(got) != 0 {
				t.Fatalf("want native fallback, got %q", got)
			}
			for _, want := range test.want {
				if !completionContains(got, want) {
					t.Errorf("missing %q in %q", want, got)
				}
			}
			for _, omit := range test.omit {
				if completionContains(got, omit) {
					t.Errorf("unsupported %q in %q", omit, got)
				}
			}
		})
	}
	t.Run("caller IFS preserved", func(t *testing.T) {
		output := run("-c", `. "$1"; IFS=:; COMP_WORDS=(logc ''); COMP_CWORD=1; _logc_completion; [[ $IFS == : ]] || exit 1; printf '%s\n' "${COMPREPLY[@]}"`, "bash", script)
		if !completionContains(strings.Fields(output), "--all") {
			t.Fatalf("custom IFS broke candidates: %q", output)
		}
	})
	t.Run("cursor before later words", func(t *testing.T) {
		output := run("-c", `. "$1"; COMP_WORDS=(logc -m '' docker); COMP_CWORD=2; _logc_completion; printf '%s\n' "${COMPREPLY[@]}"`, "bash", script)
		if strings.TrimSpace(output) != "" {
			t.Fatalf("value position has candidates: %q", output)
		}
	})
	for _, mode := range []string{"root", "watch", "system", "docker", "ls"} {
		options := []string{"--since", "-C", "--context", "-n", "--lines", "-m", "--match", "--exclude", "--category", "--module"}
		if mode == "docker" {
			options = []string{"--since", "--until", "--tail", "-n", "-fn", "-tn", "-m", "--match", "-C", "--context"}
		} else if mode == "ls" {
			options = []string{"--category", "--module"}
		}
		for _, option := range options {
			for _, value := range []string{"", "--", "wat", "doc"} {
				t.Run(mode+option+value, func(t *testing.T) {
					words := []string{"logc"}
					if mode != "root" {
						words = append(words, mode)
					}
					words = append(words, option, value)
					args := append([]string{"-c", `. "$1"; shift; PATH=/nonexistent; COMP_WORDS=("$@"); COMP_CWORD=$((${#COMP_WORDS[@]} - 1)); _logc_completion; printf '%s\n' "${COMPREPLY[@]}"`, "bash", script}, words...)
					if got := strings.TrimSpace(run(args...)); got != "" {
						t.Fatalf("value position has candidates: %q", got)
					}
				})
			}
		}
	}
}

func completionContains(words []string, value string) bool {
	for _, word := range words {
		if word == value {
			return true
		}
	}
	return false
}

func TestCompletionCLI(t *testing.T) {
	root := t.TempDir()
	binary := filepath.Join(root, "logc")
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	if output, err := exec.CommandContext(ctx, "go", "build", "-o", binary, ".").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, output)
	}
	config := filepath.Join(root, "invalid.conf")
	if err := os.WriteFile(config, []byte("lines=invalid\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	for _, test := range []struct {
		args []string
		code int
	}{
		{[]string{"completion", "bash"}, 0}, {[]string{"completion"}, 2},
		{[]string{"completion", "fish"}, 2}, {[]string{"completion", "bash", "extra"}, 2},
		{[]string{"completion", "--help"}, 0},
	} {
		t.Run(strings.Join(test.args, "_"), func(t *testing.T) {
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			defer cancel()
			command := exec.CommandContext(ctx, binary, test.args...)
			command.Env = append(os.Environ(), "LOGC_CONFIG="+config, "PATH=/nonexistent")
			var stdout, stderr bytes.Buffer
			command.Stdout, command.Stderr = &stdout, &stderr
			err := command.Run()
			code := 0
			if err != nil {
				var exit *exec.ExitError
				if !errors.As(err, &exit) {
					t.Fatal(err)
				}
				code = exit.ExitCode()
			}
			if code != test.code || strings.Contains(stderr.String(), "invalid lines") {
				t.Fatalf("code=%d, want %d; stderr=%s", code, test.code, &stderr)
			}
			if reflect.DeepEqual(test.args, []string{"completion", "bash"}) {
				if stdout.String() != bashCompletionScript || stderr.Len() != 0 {
					t.Fatalf("stdout=%q stderr=%q", &stdout, &stderr)
				}
			} else if stdout.Len() != 0 || !strings.Contains(stderr.String(), "usage: logc completion bash") {
				t.Fatalf("stdout=%q stderr=%q", &stdout, &stderr)
			}
		})
	}
	if err := os.WriteFile(config, nil, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "completion"), []byte("COMPLETION_ESCAPE_OK\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{{"./completion", "COMPLETION_ESCAPE_OK", "--all", "--no-color"}, {"-m", "COMPLETION_ESCAPE_OK", "--all", "--no-color", "--", "completion"}} {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		command := exec.CommandContext(ctx, binary, args...)
		command.Dir = root
		command.Env = append(os.Environ(), "LOGC_CONFIG="+config)
		output, err := command.CombinedOutput()
		cancel()
		if err != nil || !strings.Contains(string(output), "COMPLETION_ESCAPE_OK") {
			t.Fatalf("escaped target %q: %v\n%s", args, err, output)
		}
	}
}
